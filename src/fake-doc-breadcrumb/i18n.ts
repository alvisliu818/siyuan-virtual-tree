export const language: Record<string, string> = {...zh_CN};

export function initLanguage(): void {
    try {
        const lang = (window as any)?.siyuan?.config?.langs?.currentLang || navigator.language || "";
        const target: Record<string, string> = /^zh/i.test(lang) ? zh_CN : en_US;
        for (const k of Object.keys(language)) delete language[k];
        Object.assign(language, target);
    } catch {
        // 读取语言失败时保持默认 zh_CN
    }
}
